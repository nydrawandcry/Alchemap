-- Начальная схема локальной базы. Выполняется приложением автоматически.
-- IF NOT EXISTS позволяет повторить создание после прерванной установки.

CREATE TABLE IF NOT EXISTS ingredients (
                                           id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           name VARCHAR_IGNORECASE(100) NOT NULL UNIQUE,
    category VARCHAR(60) NOT NULL,
    description VARCHAR(500) NOT NULL,
    healing DECIMAL(7,2) NOT NULL DEFAULT 0,
    toxicity DECIMAL(7,2) NOT NULL DEFAULT 0,
    fire DECIMAL(7,2) NOT NULL DEFAULT 0,
    frost DECIMAL(7,2) NOT NULL DEFAULT 0,
    volatility DECIMAL(7,2) NOT NULL DEFAULT 0,
    magic DECIMAL(7,2) NOT NULL DEFAULT 0,
    stability DECIMAL(7,2) NOT NULL DEFAULT 0,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
    );

CREATE TABLE IF NOT EXISTS operations (
                                          code VARCHAR(30) PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(500) NOT NULL
    );

CREATE TABLE IF NOT EXISTS experiments (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           name VARCHAR(160) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    result_name VARCHAR(160) NOT NULL,
    result_type VARCHAR(80) NOT NULL,
    result_description VARCHAR(800) NOT NULL,
    healing DECIMAL(9,2) NOT NULL DEFAULT 0,
    toxicity DECIMAL(9,2) NOT NULL DEFAULT 0,
    fire DECIMAL(9,2) NOT NULL DEFAULT 0,
    frost DECIMAL(9,2) NOT NULL DEFAULT 0,
    volatility DECIMAL(9,2) NOT NULL DEFAULT 0,
    magic DECIMAL(9,2) NOT NULL DEFAULT 0,
    stability DECIMAL(9,2) NOT NULL DEFAULT 0,
    state VARCHAR(80) NOT NULL,
    temperature VARCHAR(80) NOT NULL,
    color VARCHAR(80) NOT NULL
    );

CREATE TABLE IF NOT EXISTS experiment_steps (
                                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                experiment_id BIGINT NOT NULL,
                                                step_order INT NOT NULL,
                                                step_type VARCHAR(20) NOT NULL CHECK (step_type IN ('INGREDIENT', 'ACTION')),
    ingredient_id INT,
    quantity DECIMAL(8,2),
    action_code VARCHAR(30),
    display_text VARCHAR(220) NOT NULL,
    CONSTRAINT fk_step_experiment FOREIGN KEY (experiment_id)
    REFERENCES experiments(id) ON DELETE CASCADE,
    CONSTRAINT fk_step_ingredient FOREIGN KEY (ingredient_id)
    REFERENCES ingredients(id) ON DELETE SET NULL,
    CONSTRAINT fk_step_action FOREIGN KEY (action_code)
    REFERENCES operations(code) ON DELETE RESTRICT,
    CONSTRAINT uq_experiment_order UNIQUE (experiment_id, step_order)
    );

CREATE TABLE IF NOT EXISTS saved_recipes (
                                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             experiment_id BIGINT NOT NULL UNIQUE,
                                             name VARCHAR(160) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_recipe_experiment FOREIGN KEY (experiment_id)
    REFERENCES experiments(id) ON DELETE CASCADE
    );

CREATE TABLE IF NOT EXISTS potion_rules (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            name VARCHAR(160) NOT NULL,
    result_type VARCHAR(80) NOT NULL,
    description VARCHAR(800) NOT NULL,
    priority INT NOT NULL DEFAULT 100 CHECK (priority BETWEEN 0 AND 10000),
    enabled BOOLEAN NOT NULL DEFAULT TRUE
    );

CREATE TABLE IF NOT EXISTS potion_rule_conditions (
                                                      rule_id BIGINT NOT NULL,
                                                      condition_order INT NOT NULL,
                                                      alternative_group INT NOT NULL CHECK (alternative_group BETWEEN 1 AND 99),
    metric VARCHAR(40) NOT NULL,
    comparison VARCHAR(4) NOT NULL,
    other_metric VARCHAR(40),
    multiplier DOUBLE PRECISION NOT NULL DEFAULT 1,
    threshold DOUBLE PRECISION NOT NULL DEFAULT 0,
    PRIMARY KEY (rule_id, condition_order),
    CONSTRAINT fk_condition_potion_rule FOREIGN KEY (rule_id)
    REFERENCES potion_rules(id) ON DELETE CASCADE
    );
